/**
 * Subfolder of "web/fonts" holding the downloaded font files,
 * so it is obvious to the user that its contents are generated.
 */
export const GENERATED_DIR = "generated";

/**
 * Path from the compiled stylesheet in "web/css" to the theme's "web/fonts".
 */
export const FONTS_URL_BASE = "../fonts";

const FONT_EXTENSIONS = ["woff2", "woff", "ttf", "otf", "eot", "svg"];

const HEADER = `/**
 * This file is automatically generated.
 * Do not edit this file!
 *
 * The font files it references live in "web/fonts/generated"
 * and are generated as well. To change them, update the "fonts"
 * configuration in hyva.config.json and run "npx hyva-fonts".
 */
`;

const isObject = (value) => value !== null && typeof value === "object" && !Array.isArray(value);
const asList = (value) => (typeof value === "string" ? [value] : value);

/**
 * Accept a single string wherever a list of strings is expected, such as
 * `"src": "acme.woff2"`, which hyva.config.json has always allowed.
 *
 * @param {unknown} fonts - Raw `fonts` config.
 * @returns {unknown} the same config, with those strings wrapped in a list
 */
function withLists(fonts) {
    if (!Array.isArray(fonts)) return fonts;

    return fonts.map((font) => {
        if (!isObject(font)) return font;

        const list = { ...font };
        for (const key of ["styles", "subsets", "fallbacks"]) {
            if (key in list) list[key] = asList(list[key]);
        }
        if (Array.isArray(list.variants)) {
            list.variants = list.variants.map((variant) =>
                isObject(variant) && "src" in variant ? { ...variant, src: asList(variant.src) } : variant
            );
        }
        return list;
    });
}

/**
 * Validate and normalize the `fonts` array of hyva.config.json.
 *
 * @param {unknown} fonts - Raw `fonts` config.
 * @returns {{ fonts: Object[], errors: string[], valid: boolean }}
 */
export const normalizeFonts = (fonts) => normalize(withLists(fonts ?? []));

/**
 * Turn the faces a provider resolved earlier into a family of the "local"
 * provider, so it is rendered and measured from the files on disk without
 * asking the provider again.
 *
 * @param {Object} font - Normalized font family.
 * @param {Object[]} faces - Faces from the manifest, with `files` relative to "web/fonts".
 * @returns {Object} font family config
 */
function fromManifest(font, faces) {
    const defined = (values) =>
        Object.fromEntries(Object.entries(values).filter(([, value]) => value != null));

    return defined({
        provider: "local",
        name: font.name,
        cssVariable: font.cssVariable,
        cssSelector: font.cssSelector,
        fallbacks: font.fallbacks,
        display: font.display,
        preload: font.preload,
        adjustFallback: font.adjustFallback,
        variants: faces.map((face) =>
            defined({
                src: face.files,
                weight: face.weight,
                style: face.style,
                stretch: face.stretch,
                unicodeRange: face.unicodeRange,
            })
        ),
    });
}

/**
 * Resolve a single family. Each family gets its own run, so its warnings can
 * be told apart from those of the others.
 *
 * A family whose files are already on disk, and whose config has not changed
 * since they were fetched, is rebuilt from the manifest without touching the
 * network. Anything else is requested from its provider, and a provider that
 * cannot be reached falls back to the files already present.
 *
 * @param {Object} font - Normalized font family.
 * @param {Object} raw - The same family as configured in hyva.config.json.
 * @param {Object} options
 * @param {string} options.fontsDir - Absolute path to the theme's "web/fonts" folder.
 * @param {Object} [options.previous] - Manifest entry of this family.
 * @param {boolean} options.force - Ignore the manifest and re-download.
 * @param {typeof fetch} options.fetchImpl
 * @param {Map<string, Object>} options.providers - Providers by id.
 * @returns {Promise<{ family: Object, entry: Object|null, cached: boolean,
 *          confirmed: boolean, downloaded: number, warnings: string[] }>} where
 *          `confirmed` means the files this family needs are known for certain
 */
async function resolveFamily(font, raw, { fontsDir, previous, force, fetchImpl, providers }) {
    const provider = providers.get(font.provider);

    const fromDisk = async (warnings) => {
        const result = await generate([fromManifest(font, previous.faces)], { storage: fontsDir });
        return {
            family: { ...result.families[0], font },
            entry: previous,
            cached: true,
            confirmed: !warnings.length,
            downloaded: 0,
            warnings: [...warnings, ...result.warnings],
        };
    };

    if (!provider.remote) {
        const result = await generate([raw], { storage: fontsDir });
        return {
            family: result.families[0],
            entry: null,
            cached: false,
            confirmed: true,
            downloaded: 0,
            warnings: result.warnings,
        };
    }

    if (!force && previous?.key === cacheKey(font) && facesArePresent(previous.faces, fontsDir)) {
        return fromDisk([]);
    }

    const result = await generate([raw], {
        storage: path.join(fontsDir, GENERATED_DIR),
        force,
        fetch: fetchImpl,
    });
    const [family] = result.families;

    if (!family.faces.length && facesArePresent(previous?.faces, fontsDir)) {
        // Keep the reason, without the "Skipped" line it comes with.
        const reasons = result.warnings.map((warning) => warning.replace(/^[^\n]*\n\s*/, ""));
        return fromDisk([
            `Could not reach ${provider.label} for "${font.name}", using the font files already in web/fonts/${GENERATED_DIR}.\n  ${reasons.join("\n  ")}`,
        ]);
    }

    const faces = family.faces.map((face) => ({
        ...face,
        files: face.files.map((file) => `${GENERATED_DIR}/${file}`),
    }));

    return {
        family: { ...family, faces },
        entry: faces.length ? { key: cacheKey(font), faces } : null,
        cached: false,
        confirmed: faces.length > 0 && result.downloads.every((download) => download.status !== "failed"),
        downloaded: result.downloaded(),
        warnings: result.warnings,
    };
}

/**
 * Delete files in "web/fonts/generated" that the current config no longer uses.
 *
 * @param {string} fontsDir - Absolute path to the theme's "web/fonts" folder.
 * @param {Set<string>} keep - File names to keep.
 * @returns {Promise<string[]>} removed file names
 */
export async function pruneGeneratedFonts(fontsDir, keep) {
    const generatedDir = path.join(fontsDir, GENERATED_DIR);
    if (!existsSync(generatedDir)) return [];

    const entries = await fs.readdir(generatedDir, { withFileTypes: true });
    const stale = entries
        .filter(
            (entry) =>
                entry.isFile() &&
                entry.name !== MANIFEST_FILE &&
                FONT_EXTENSIONS.includes(entry.name.split(".").pop().toLowerCase()) &&
                !keep.has(entry.name)
        )
        .map((entry) => entry.name);

    await Promise.all(
        stale.map((name) => fs.rm(path.join(generatedDir, name), { force: true }))
    );

    return stale;
}

/**
 * Generate the font stylesheet and font files for a theme.
 *
 * @param {Object} [config] - Parsed hyva.config.json.
 * @param {Object} options
 * @param {string} options.tailwindDir - Absolute path to the theme's "web/tailwind" folder.
 * @param {string} [options.fontsDir] - Absolute path to the theme's "web/fonts" folder.
 * @param {string} [options.themeDir] - Absolute path to the theme root, holding its layout files.
 * @param {boolean} [options.force=false] - Ignore the manifest and re-download.
 * @param {typeof fetch} [options.fetchImpl] - Injectable fetch, used by the tests.
 * @returns {Promise<{ css: string, preload: string|null, layout: Object|null,
 *          families: Object[], downloaded: number, cached: number,
 *          removed: string[], warnings: string[] }>}
 */
export async function generateFonts(
    config = {},
    {
        tailwindDir,
        fontsDir = path.resolve(tailwindDir, "../fonts"),
        themeDir = path.resolve(tailwindDir, "../.."),
        force = false,
        fetchImpl = fetch,
    }
) {
    const raw = withLists(config.fonts ?? []);
    const { fonts, errors } = normalize(raw);

    if (errors.length) {
        throw new Error(`Invalid "fonts" configuration:\n  ${errors.join("\n  ")}`);
    }

    const generatedDir = path.join(fontsDir, GENERATED_DIR);
    const manifest = readManifest(generatedDir);
    const providers = new Map(defaultProviders().map((provider) => [provider.id, provider]));
    const runs = await Promise.all(
        fonts.map((font, index) =>
            resolveFamily(font, raw[index], {
                fontsDir,
                previous: manifest.families?.[font.cssVariable],
                force,
                fetchImpl,
                providers,
            })
        )
    );

    const entries = Object.fromEntries(
        runs.filter((run) => run.entry).map((run) => [run.family.font.cssVariable, run.entry])
    );
    const warnings = runs.flatMap((run) => run.warnings);
    const result = new Result(runs.map((run) => run.family), {
        urlBase: FONTS_URL_BASE,
        // Reuse the tokens selector, so a Tailwind v3 theme that generates its
        // tokens into ":root" gets its font variables in the same place.
        cssSelector: config.tokens?.cssSelector || "@theme",
    });

    if (fonts.length) await writeManifest(generatedDir, entries);

    // An empty stylesheet is still written when nothing is configured, so a
    // theme that imports it keeps building after its last font is removed.
    const css = fonts.length
        ? `${HEADER}\n${result.css()}\n`
        : `${HEADER}\n/* No "fonts" are configured in hyva.config.json. */\n`;

    const cssDir = path.join(tailwindDir, "generated");
    await fs.mkdir(cssDir, { recursive: true });
    await fs.writeFile(path.join(cssDir, "hyva-fonts.css"), css);

    // Kept with the font files it points at rather than with the stylesheet,
    // and removed rather than left behind when nothing asks to be preloaded,
    // so a stale copy cannot be pasted into a theme long after the fact.
    const preloads = result.preloads();
    const preload = renderPreloadXml(preloads);
    const preloadFile = path.join(generatedDir, PRELOAD_FILE);
    if (preload) {
        await fs.mkdir(generatedDir, { recursive: true });
        await fs.writeFile(preloadFile, preload);
    } else {
        await fs.rm(preloadFile, { force: true });
    }

    // Pruning needs to know the complete desired state. When a family could
    // not be confirmed it is not known, so the files stay put rather than risk
    // deleting a font that this run simply could not reach.
    const keep = new Set(
        Object.values(entries).flatMap((entry) =>
            entry.faces.flatMap((face) => face.files.map((file) => path.basename(file)))
        )
    );
    const removed = runs.every((run) => run.confirmed)
        ? await pruneGeneratedFonts(fontsDir, keep)
        : [];

    // The markers in the theme's layout file are the opt in. Without them
    // nothing is touched, and the generated snippet is all the user gets.
    let layout = null;
    try {
        layout = await updateLayout(preloads, { themeDir });
    } catch (error) {
        warnings.push(
            `Could not update the preload hints in the theme's layout file.\n  ${error.message}`
        );
    }

    return {
        css,
        preload,
        layout,
        families: result.families,
        downloaded: runs.reduce((total, run) => total + run.downloaded, 0),
        cached: runs.filter((run) => run.cached).length,
        removed,
        warnings,
    };
}
