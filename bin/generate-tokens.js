import fs from "node:fs/promises";
import path from "node:path";
import { cwd, exit } from "node:process";
import { consoleError, consoleWarn, getJsonFile, getTextFile } from "../src/utils/index.js";
import fromTokens from "@fylgja/props-builder/src/from-tokens.js";
import toStyleTokens from "@fylgja/props-builder/src/to-style.js";
import { stripPrefixPath, renameKeys } from "@fylgja/props-builder/src/utils.js";

const currentFolderName = path.basename(cwd());
if (currentFolderName !== "tailwind") {
    consoleError(
        `Hyvä Tokens should be run from a "tailwind" directory\nto ensure everthing is generated in the correct location.`
    );
    exit(1);
}

const hyvaConfig = getJsonFile("hyva.config.json");
const hyvaConfigTokens = hyvaConfig?.tokens || {};

if (hyvaConfigTokens?.src && hyvaConfigTokens.src.startsWith("http")) {
    consoleError(
        "Design Tokens source must be a local path, external URLs are not allowed!"
    );
    exit(1);
}

if (hyvaConfigTokens?.src && hyvaConfigTokens?.values) {
    consoleWarn(
        "Design Tokens src and values cannot be both defined. ignoring src."
    );
}

const designTokensFile = hyvaConfigTokens?.src || "design.tokens.json";
const isMarkdownSrc = designTokensFile.trim().toLowerCase().endsWith(".md");

if (
    hyvaConfigTokens?.src &&
    !hyvaConfigTokens.src.trim().toLowerCase().endsWith(".json") &&
    !isMarkdownSrc
) {
    consoleError(
        `Design Tokens src must be a JSON or Markdown file. Received: '${hyvaConfigTokens.src}'`
    );
    exit(1);
}

const designTokens = hyvaConfigTokens?.values
    || (isMarkdownSrc ? getTextFile(designTokensFile) : getJsonFile(designTokensFile));
// A Markdown source is assumed to be a Google Stitch export, since that's the only Markdown format supported so far.
const tokensFormat = hyvaConfigTokens?.format || (isMarkdownSrc ? "stitch" : "default");
const cssSelector = hyvaConfigTokens?.cssSelector || "@theme";
const mediaDark = hyvaConfigTokens?.mediaDark || "@media (prefers-color-scheme: dark)";

if (!designTokens) {
    exit(0);
}

if (!isMarkdownSrc && typeof designTokens !== "object") {
    consoleError(
        `This is not a valid Design Tokens file/config.\nPlease ensure it contains a valid design tokens (JSON) format.`
    );
    exit(1);
}

let plainTokens = fromTokens(designTokens, tokensFormat);
plainTokens = stripPrefixPath(plainTokens, hyvaConfigTokens?.stripPrefix);
plainTokens = renameKeys(plainTokens, hyvaConfigTokens?.rename);
const styleTokens = toStyleTokens(plainTokens, { selector: cssSelector, mediaDark });
const hyvaTokensCSS = `/**
 * This file is automatically generated.
 * Do not edit this file!
 */\n\n${styleTokens}\n`;

(async () => {
    try {
        await fs.mkdir(path.join(cwd(), "generated"), { recursive: true });
        await fs.writeFile(
            path.join(cwd(), "generated/hyva-tokens.css"),
            hyvaTokensCSS
        );
    } catch (err) {
        consoleError(
            "Failed to generate hyva-tokens.css:\n" +
                (err && err.stack ? err.stack : err)
        );
        exit(1);
    }
})();
